    /**
     * Execute the console command.
     *
     * @return int
     */
    public function handle()
    {
        $orders = Opencart::orders(['filter_status' => Opencart::searchStatuses('sent_invoiced_to_sexp_order')]);
        $order_fatured = $this->ordersFatured();
        //$order_fatured = [];
       // dd($order_fatured);


        foreach ($orders as $order) {

            $order_id = $order['order_id'];
            $this->info('Iniciado Processo de envio do pedido: '.$order_id);

            sleep(2);

            //arrumar pedidos parados faturados fora do fluxo normal
            if(!empty( $order_fatured[$order_id])
                && !empty($order_fatured[$order_id]['nf'])
                && !empty($order_fatured[$order_id]['rastreio'])
            ){
                $this->log($order_id.'-baseado em planilha');

                $this->updateOpencartOrderStatus(
                        $order_id, 
                        $order_fatured[$order_id]['nf'],
                        $order_fatured[$order_id]['rastreio']
                    );                
                var_dump('Enviou baseado na planilha');
                continue;
            }
           // dd('parou');

            $invoiced = Erp::find($order_id);

            if ($invoiced) {
                $sexpOrder = Sexp::getOrder($order_id);
                
                if ($sexpOrder['status']['codigo'] == '5') {
                    $this->updateOpencartOrderStatus($order_id, $invoiced['NOTA'], $sexpOrder['numeroPostagem']);
                }else{
                    var_dump('Não Enviou: '.$order_id);
                }
            }
            // else{               
            //     var_dump('SEM NF: '.$order_id);
            //     Opencart::orderHistory($order_id, [
            //         'order_status_id' => Opencart::updateStatuses('error_send_to_sexp_without_nf'),
            //         'comment' => "Ao tentar notificar o envio do pedido ao cliente, não foi possivel encontrar o Numero da NF na VIEW 'TBL_View_PedidosMedalhas_Faturados'. Assim que corrigir voltar ao Status de Aguardando Coleta ",
            //         'notify' => false,
            //     ]);                

            // }
        }
    }

    private function updateOpencartOrderStatus(int $orderId, string $invoiceNumber, string $trackingNumber)
    {

        $this->log($orderId);
        var_dump('Alterou status: '.$orderId);
        Opencart::orderHistory($orderId, [
            'order_status_id' => Opencart::updateStatuses('finished_order'),
            'comment' => "
                Seu <b>pedido {$orderId}</b> foi enviado. <br/> 
                Código de Rastreamento: 
                <b>Código de Rastreamento:</b> {$trackingNumber} <a href='https://cmb.pontualcargo.com.br/?codigoRastreamento={$trackingNumber}' target='_blank'>Clique aqui para acompanhamento</a>, ou utilize a URL abaixo.<br /> 
                
                <a href='https://cmb.pontualcargo.com.br/?codigoRastreamento={$trackingNumber}' target='_blank'>https://cmb.pontualcargo.com.br/?codigoRastreamento={$trackingNumber}</a><br>

                <a href='https://cmb.pontualcargo.com.br/?codigoRastreamento={$trackingNumber}' target='_blank'>{$trackingNumber}</a>
                <b>Número da Nota Fiscal:</b> {$invoiceNumber}
            ",
            'notify' => true,
        ]);
    }

    public function log(string $log)
